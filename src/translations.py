def get_current_language() -> str:
    """Gets the currently selected language code from st.session_state."""
    if "selected_language" not in st.session_state:
        st.session_state.selected_language = DEFAULT_LANGUAGE
    return st.session_state.selected_language


def set_language(lang_code: str):
    """Sets the active language code in st.session_state."""
    if lang_code in SUPPORTED_LANGUAGES:
        st.session_state.selected_language = lang_code


def t(key: str, lang: str = None) -> str:
    """
    Translates a key into the active or requested language.
    Falls back gracefully to English if translation is missing.
    """
    if lang is None:
        lang = get_current_language()
    
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key
    
    return entry.get(lang) or entry.get("en") or key


def get_crop_name(crop: str, lang: str = None) -> str:
    """
    Returns the localized display name for a crop in the chosen Indian language.
    """
    if lang is None:
        lang = get_current_language()
    
    crop_info = CROP_TRANSLATIONS.get(crop)
    if not crop_info:
        return crop
    
    return crop_info.get(lang) or crop_info.get("en") or crop


def render_language_selector():
    """
    Renders an elegant, high-contrast language selector dropdown
    designed for farmers and traders across Indian regions.
    """
    current_lang = get_current_language()
    
    options = list(SUPPORTED_LANGUAGES.keys())
    
    def format_lang(code):
        meta = SUPPORTED_LANGUAGES[code]
        return f"{meta['flag']} {meta['native']} ({meta['name']})"
    
    current_idx = options.index(current_lang) if current_lang in options else 1

    st.markdown(
        """
        <div style="background: rgba(255,255,255,0.08); padding: 0.5rem 0.75rem; border-radius: 8px; margin-bottom: 0.6rem; border: 1px solid rgba(255,255,255,0.12);">
            <div style="color: #FBBF24; font-size: 0.8rem; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 0.2rem;">
                🌐 भाषा / SELECT LANGUAGE
            </div>
        </div>
        """,
        unsafe_allow_html=True
    )
    
    chosen = st.selectbox(
        label="Select Language",
        options=options,
        index=current_idx,
        format_func=format_lang,
        label_visibility="collapsed",
        key="lang_selector_widget"
    )
    
    if chosen != current_lang:
        st.session_state.selected_language = chosen
        st.rerun()
